#!/usr/bin/env node
/**
 * One-time setup: registers YOUR OWN GitHub App (read-only) through GitHub's
 * manifest flow and writes apps/editor/.env.local. Nothing is sent anywhere
 * except github.com / api.github.com. The app's private key is not stored:
 * the editor only needs the OAuth client id and secret.
 *
 *   node scripts/setup-github-app.mjs --name readmeops-yourname [--url http://localhost:3000]
 */
import { randomBytes } from "node:crypto";
import { existsSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { createServer } from "node:http";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const { values } = parseArgs({
  options: {
    name: { type: "string" },
    url: { type: "string", default: "http://localhost:3000" },
    port: { type: "string", default: "3456" },
    org: { type: "string" },
    force: { type: "boolean", default: false },
  },
});

const envPath = join(dirname(fileURLToPath(import.meta.url)), "..", ".env.local");
if (existsSync(envPath) && !values.force) {
  console.error(`${envPath} already exists. Re-run with --force to replace it.`);
  process.exit(1);
}
if (!values.name) {
  console.error("Pass a unique app name, e.g. --name readmeops-<your-login>");
  process.exit(1);
}

const appUrl = values.url.replace(/\/+$/, "");
const port = Number(values.port);
const state = randomBytes(24).toString("base64url");
const manifest = {
  name: values.name,
  url: appUrl,
  hook_attributes: { url: `${appUrl}/unused-webhook`, active: false },
  redirect_url: `http://localhost:${port}/callback`,
  callback_urls: [`${appUrl}/api/auth/callback`],
  public: true,
  request_oauth_on_install: true,
  default_permissions: { contents: "read", metadata: "read", pull_requests: "read", issues: "read" },
  default_events: [],
};
const target = values.org
  ? `https://github.com/organizations/${encodeURIComponent(values.org)}/settings/apps/new?state=${state}`
  : `https://github.com/settings/apps/new?state=${state}`;

const esc = (s) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

const server = createServer(async (req, res) => {
  const url = new URL(req.url ?? "/", `http://localhost:${port}`);
  if (url.pathname === "/") {
    res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" });
    res.end(`<!doctype html><meta charset="utf-8"><title>readmeops setup</title>
<body style="font:16px system-ui;max-width:640px;margin:48px auto">
<h1>Create your readmeops GitHub App</h1>
<p>This creates a <b>read-only</b> GitHub App owned by you (Contents, Issues, Pull requests and Metadata, all read-only; no webhooks). People sign in with it only to see their own private work in the editor.</p>
<form method="post" action="${esc(target)}"><input type="hidden" name="manifest" value="${esc(JSON.stringify(manifest))}">
<button type="submit" style="font-size:16px;padding:10px 18px">Continue on GitHub</button></form></body>`);
    return;
  }
  if (url.pathname === "/callback") {
    const code = url.searchParams.get("code");
    if (!code || url.searchParams.get("state") !== state) {
      res.writeHead(400).end("state mismatch; start again");
      return;
    }
    try {
      const r = await fetch(`https://api.github.com/app-manifests/${encodeURIComponent(code)}/conversions`, {
        method: "POST",
        headers: { Accept: "application/vnd.github+json", "User-Agent": "readmeops-setup" },
      });
      const app = await r.json();
      if (!r.ok || !app.client_id || !app.client_secret) throw new Error(app.message ?? `HTTP ${r.status}`);
      const env = [
        "# Generated by scripts/setup-github-app.mjs. Keep this file private (it is git-ignored).",
        `GITHUB_APP_CLIENT_ID=${app.client_id}`,
        `GITHUB_APP_CLIENT_SECRET=${app.client_secret}`,
        `GITHUB_APP_SLUG=${app.slug}`,
        `SESSION_SECRET=${randomBytes(48).toString("base64url")}`,
        `APP_URL=${appUrl}`,
        "# Add GITHUB_TOKEN (public read-only access) to load real profiles. See .env.example.",
        "GITHUB_TOKEN=",
        "",
      ].join("\n");
      await writeFile(envPath, env, { mode: 0o600 });
      res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" });
      res.end(`<body style="font:16px system-ui;max-width:640px;margin:48px auto"><h1>Done</h1><p>Created <b>${esc(app.slug)}</b> and wrote .env.local. You can close this tab and run <code>npm run dev</code>.</p></body>`);
      console.log(`\nCreated GitHub App "${app.slug}" and wrote ${envPath}`);
      console.log("The private key was not saved; the editor does not need it.");
      setTimeout(() => process.exit(0), 300);
    } catch (err) {
      res.writeHead(500).end(`conversion failed: ${err.message}`);
      console.error("conversion failed:", err.message);
    }
    return;
  }
  res.writeHead(404).end();
});

server.listen(port, "127.0.0.1", () => {
  console.log(`Open http://localhost:${port} in your browser to create the GitHub App.`);
});
